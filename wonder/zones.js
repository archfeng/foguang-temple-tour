/* 建筑禁入区：世界坐标 [x0,x1,z0,z1]（数据的 z 已按场景约定取反）。
 * 园林撒树和「事后清障」必须用同一份表：先前只有清障认识这些框，
 * 而清障又故意跳过 wonder 自己生成的树，于是竹丛照样从殿里长出来。
 * 现在植被在生成前先问一遍，清障则负责收拾原场景那批烘焙树。
 */
export const NO_PLANT_BOXES = [
  [-16.8, -3.0,   8.8, 16.8],   // 庭堂
  [-17.0, -3.0,  18.2, 25.8],   // 客堂
  [-14.0, -6.0,  22.0, 32.5],   // 券门（森会祗园门）
  [-38.2, -23.8, 16.2, 25.8],   // 伽蓝殿
  [-49.0, -15.2,-28.6, -9.6],   // 文殊殿
  [-18.2, -3.8, -28.8,-19.2],   // 香风花雨楼
  [  5.2, 18.8, -30.0,-22.0],   // 万善堂
  [  5.8, 18.2,  21.0, 28.8],   // 关帝殿
  [  9.4, 34.6, -20.8, 20.8],   // 东大殿
  [-52.6,-45.4,  -5.8,  5.8],   // 山门
  // 券门后面的通路：原先门洞里望出去全是树干，一道门形同虚设
  [-18.0, -1.0,  29.0, 37.5],
  // 二进院南向挡土墙（x≈-7，沿 z 走的六米高砖墙，墙上有三个砖券洞）
  [-10.2, -4.0, -16.5, 15.0]
];

export function inNoPlant(x, z, pad = 1.6){
  for (const b of NO_PLANT_BOXES)
    if (x > b[0]-pad && x < b[1]+pad && z > b[2]-pad && z < b[3]+pad) return true;
  return false;
}
